from operator import add
from typing import Annotated, Literal

from pydantic import BaseModel, Field

class AgentSchema(BaseModel):
    messages: Annotated[list,add] = Field(..., description="List of messages to be processed by the agent")
    user_question: str = Field(..., description="User's question or query that needs to be processed by the agent")
    curated_question: str = Field(..., description="Curated question generated by the agent based on the user input and messages")   
    prompt_query_context: str = Field(..., description="Contextual information on SQL Database and data engineering to assist the agent in generating relevant responses")
    is_safe: Literal['safe', 'unsafe'] = Field(..., description="Indicates whether the SQL query generated by the agent is safe or unsafe based on the curated question and prompt query context")
    generated_sql_query: str = Field(..., description="SQL query generated by the agent based on the curated question and prompt query context")
    comments: str = Field(..., description="Comments or feedback provided by the judger regarding the safety of the SQL query")
    sql_query_results: str = Field(..., description="Results of the SQL query executed against the database, providing relevant information to the agent for generating responses")
    final_response: str = Field(..., description="Final response generated by the agent based on the curated question, prompt query context, and SQL query results")

class JudgerSchema(BaseModel):
    is_safe: Literal['safe', 'unsafe'] = Field(..., description="Indicates whether the SQL query is safe or unsafe based on the evaluation criteria")
    comments: str = Field(..., description="Comments or feedback provided by the judger regarding the safety of the SQL query")