import os
import sys
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from utils.llm_pick import pick_llm
from models.schema import AgentSchema, JudgerSchema
from langchain_core.messages import HumanMessage,AIMessage
from utils.DataBase import DataBase
from sqlalchemy import text
from agents.Judger import JudgerAgent
from dotenv import load_dotenv
load_dotenv()

class SQLAnalystAgent:
    def __init__(self, level: str):
        self.llm = pick_llm(level)
        self.db = DataBase({
            "USER": os.getenv('USER'),
            "PASSWORD": os.getenv('PASSWORD'),
            "HOST": os.getenv('HOST'),
            "HOST_PORT": os.getenv('HOST_PORT'),
            "DATA_BASE": os.getenv('DATA_BASE')
        })

    def Curate_question(self, state: AgentSchema) -> AgentSchema:
        """
        Curates a question based on the provided messages.

        Args:
            messages (list): List of messages to be processed by the agent.

        Returns:
            str: Curated question generated by the agent.
        """
        # Implement your logic to curate a question based on the messages
        user_question = state.user_question
        curated_question = self.llm.invoke({"curate the Question": user_question}).content[0].get("text")
        state.curated_question = curated_question
        state.messages.append(HumanMessage(content=curated_question))
        return state
    
    def promptQueryContext(self, state: AgentSchema) -> AgentSchema:
        """
        Generates a prompt query context based on the curated question.

        Args:
            curated_question (str): Curated question generated by the agent.

        Returns:
            str: Prompt query context generated by the agent.
        """
        # Implement your logic to generate a prompt query context based on the curated question
        curated_question = state.curated_question
        prompt = f"""
                You are an intelligent database assistant specialized in SQL databases,
                database systems, and data engineering.

                Your task is to answer the user's question accurately using the
                provided database schema and your general technical knowledge.

                ========================
                USER QUESTION
                ========================
                {curated_question}

                ========================
                DATABASE CONTEXT
                ========================
                The following information describes the structure of the connected database:

                {self.db.SchemaIfo('dagent')}

                ========================
                INSTRUCTIONS
                ========================

                1. Understand the user's question before generating your response.

                2. Use the provided database schema whenever the question concerns
                the connected database.

                3. Never invent or assume the existence of tables, columns,
                relationships, or database objects that are not present
                in the provided schema.

                4. If the requested information cannot be determined from the schema,
                explicitly explain what information is missing.

                5. Generate SQL query without an additional explanation,:
                

                6. When answering general questions about SQL, databases,
                or data engineering, use your technical knowledge even if
                the provided schema is not directly relevant.

                7. Keep responses clear, accurate, and structured.
                Include code examples when they help explain the answer.

                8. Do not claim to have executed SQL queries or accessed database
                records unless execution results have actually been provided.

                9. If the user's question is ambiguous, ask for clarification
                rather than making unsupported assumptions.

                ========================
                RESPONSE
                ========================
                Provide the most relevant and accurate answer to the user's question.
                """
        state.prompt_query_context = prompt

        return state
    
    def is_safeQuery(self, state: AgentSchema) -> AgentSchema:
        """
        Evaluates the safety of the generated SQL query based on the curated question and prompt query context.

        Args:
            state (AgentSchema): The current state of the agent containing the curated question, prompt query context, and generated SQL query.
        Returns:
            JudgerSchema: The evaluation results indicating whether the SQL query is safe or unsafe.
        """
        judger = JudgerAgent(level="basic")
        state.is_safe = judger.evaluate_sql_query(state).is_safe
        state.comments = judger.evaluate_sql_query(state).comments
        return state
    
    def cancel_QueryExecution(self, state: AgentSchema) -> AgentSchema:
        """
        Cancels the execution of the SQL query if it is deemed unsafe.

        Args:
            state (AgentSchema): The current state of the agent containing the curated question, prompt query context, and generated SQL query.
        Returns:

            AgentSchema: The updated state of the agent after canceling the SQL query execution.
        """
        state.final_response=f"The SQL query is deemed unsafe and will not be executed. Comments By Judger: {state.comments}"
        state.messages=state.messages + [AIMessage(content=state.final_response)]
        return state
    def execute_Query(self, state: AgentSchema) -> AgentSchema:
        """
        Executes the SQL query if it is deemed safe.

        Args:
            state (AgentSchema): The current state of the agent containing the curated question, prompt query context, and generated SQL query.
        Returns:

            AgentSchema: The updated state of the agent after executing the SQL query and storing the results.
        """
        db_configs = {
            "USER": os.getenv('USER'),
            "PASSWORD": os.getenv('PASSWORD'),
            "HOST": os.getenv('HOST'),
            "HOST_PORT": os.getenv('HOST_PORT'),
            "DATA_BASE": os.getenv('DATA_BASE')
        }
        db = DataBase(db_configs)
        if state.is_safe == "safe":
            try:
                results = db.execute_query(state.generated_sql_query)
                state.sql_query_results = str(results)
            except Exception as e:
                print(f"Query isn't executed! due to {e}")
                
        else:
            state.final_response=f"The SQL query is deemed unsafe and will not be executed. Comments By Judger: {state.comments}"
        return state
    #representation of result
    def represent_finalResponse(self, state: AgentSchema):
        """
        Represents the final response generated by the agent based on the curated question, prompt query context,
        and SQL query results.
        Args:
            state (AgentSchema): The current state of the agent containing the curated question, prompt query context, and SQL query results.   
            Returns:
            str: The final response generated by the agent.
        """
        curated_quation = state.curated_question
        query_result = state.sql_query_results
        prompt = f"""
                    you are an SQL analyst Agent and your task is to provide a final answer 
                    based on {curated_quation} and {query_result}
                """
        response = self.llm.invoke(prompt)
        state.final_response = response
        state.messages=state.messages+ [AIMessage(content=response)]
        return state

    def setLLM(self, level: str):
        """
        Sets the LLM based on the provided level.

        Args:
            level (str): The level of the LLM to set. Can be 'basic', 'intermediate', or 'advanced'.
        """
        self.llm = pick_llm(level)
    