from langchain_core.messages import HumanMessage
from models.schema import JudgerSchema, AgentSchema
from utils.llm_pick import pick_llm
from utils.DataBase import DataBase
from dotenv import load_dotenv
load_dotenv()

class JudgerAgent:
    def __init__(self, level: str = 'basic',prompt: str = None):
        self.llm = pick_llm(level)
        self.prompt = prompt or """"
                    You are a judger agent specialized in evaluating SQL queries generated by the SQLAnalystAgent.
                    Your task is to assess Security and safety of the SQL query based on the curated question and prompt query context provided by the SQLAnalystAgent.
                    The SQL query should only be for data retrieval and should not perform any data manipulation or modification operations.
                    You should provide a clear and concise evaluation of the SQL query, indicating whether it is safe or unsafe, along with any relevant comments or feedback regarding the safety of the SQL query.
        """
    def evaluate_sql_query(self, state: AgentSchema) -> JudgerSchema:
        """
        Evaluates the safety of the generated SQL query based on the curated question and prompt query context.

        Args:
            state (AgentSchema): The current state of the agent containing the curated question, prompt query context, and generated SQL query.

            """
        LLM_judger = self.llm.with_structured_output(schema=JudgerSchema)
        return LLM_judger.invoke(
            f"{self.prompt} \n Generated SQL Query: {state.generated_sql_query}"
        ).model_dump()